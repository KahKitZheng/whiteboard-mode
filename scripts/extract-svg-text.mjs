import { chromium } from '@playwright/test'
import { readFileSync, writeFileSync } from 'node:fs'
import { basename, extname } from 'node:path'

// Usage: node scripts/extract-svg-text.mjs [input.svg]
// Stands in for the text step of a real page job (pdf.js `getTextContent` on
// a PDF): every <text> of the fixture SVG as a line box in percentages of the
// image, written next to the fixture as a `.text.ts` module. A browser does
// the measuring, since word widths need the font actually rendering.
const input = process.argv[2] ?? 'public/boardbook/waterkringloop.svg'
const name = basename(input, extname(input))

const browser = await chromium.launch()
const page = await browser.newPage()
await page.setContent(readFileSync(input, 'utf8'))
const lines = await page.evaluate(() => {
  const svg = document.querySelector('svg')
  const { width, height } = svg.viewBox.baseVal
  return Array.from(svg.querySelectorAll('text')).map((text) => {
    const box = text.getBBox()
    const round = (value) => Math.round(value * 1000) / 1000
    return {
      text: text.textContent,
      x: round((box.x / width) * 100),
      y: round((box.y / height) * 100),
      width: round((box.width / width) * 100),
      height: round((box.height / height) * 100),
      fontSize: round((parseFloat(getComputedStyle(text).fontSize) / width) * 100),
    }
  })
})
await browser.close()

const out = `src/boardbook/${name}.text.ts`
writeFileSync(
  out,
  `// Generated by scripts/extract-svg-text.mjs from ${input}. Do not edit.\nimport type { TextLine } from './TextLayer'\n\nexport const ${name.toUpperCase()}_TEXT: TextLine[] = ${JSON.stringify(lines, null, 2)}\n`,
)
console.log(`${lines.length} lines -> ${out}`)
